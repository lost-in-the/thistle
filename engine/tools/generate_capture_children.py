#!/usr/bin/env python3
"""Generate exhaustive, nonrecursive child enumeration from Prism's public schema.

Usage: python3 generate_capture_children.py /path/to/prism-1.9.0/config.json
The pinned parser remains a dependency; this helper contains no parser logic.
"""
import json
import re
import sys
from pathlib import Path

schema = json.loads(Path(sys.argv[1]).read_text())
def snake(name):
    return re.sub(r"([A-Z])", r"_\1", name).lower().lstrip("_")

def typed(field):
    kind = field.get("kind")
    return isinstance(kind, str) and kind not in ("Node", "non-void expression", "pattern expression")

lines = ["// Generated by tools/generate_capture_children.py from Prism 1.9.0 public node schema.",
         "// Exhaustive matching makes a parser schema upgrade a reviewable compiler boundary.",
         "use ruby_prism::Node;", "", 
         "pub(super) fn for_each_child<'pr>(node: &Node<'pr>, mut child: impl FnMut(Node<'pr>)) {",
         "    match node {"]
for node in schema["nodes"]:
    fields = [field for field in node.get("fields", []) if field["type"] in ("node", "node?", "node[]")]
    if not fields:
        lines.append(f"        Node::{node['name']} {{ .. }} => {{}},")
        continue
    lines.append(f"        Node::{node['name']} {{ .. }} => {{")
    lines.append(f"            let concrete = node.as_{snake(node['name'])}().expect(\"matching node variant\");")
    for field in fields:
        name = field["name"]
        conversion = ".as_node()" if typed(field) else ""
        if field["type"] == "node":
            lines.append(f"            child(concrete.{name}(){conversion});")
        elif field["type"] == "node?":
            lines.append(f"            if let Some(value) = concrete.{name}() {{ child(value{conversion}); }}")
        else:
            lines.append(f"            for value in &concrete.{name}() {{ child(value); }}")
    lines.append("        },")
lines += ["    }", "}", ""]
Path(__file__).resolve().parents[1].joinpath("src/capture_children.rs").write_text("\n".join(lines))
